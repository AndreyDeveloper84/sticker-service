def prices_text(*, telegram: bool) -> str:
    currency = "736 Stars" if telegram else "800 ₽"
    pack = "460 Stars" if telegram else "500 ₽"
    single = "100 Stars" if telegram else "100 ₽"
    return f"💰 Цены\n\n9 стикеров с надписями — {currency}\n9 стикеров без надписей — {pack}\n1 стикер — {single}"
